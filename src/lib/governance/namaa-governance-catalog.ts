export function foundingCouncilMeetingAt(completedAt:string|null|undefined){
  if(!completedAt)return null;
  const completed=new Date(completedAt);
  if(Number.isNaN(completed.getTime()))return null;
  return new Date(completed.getTime()+24*60*60*1000);
}
